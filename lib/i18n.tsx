export function useI18n() {
  const locale = useMarket((state) => state.locale);
  const setLocale = useMarket((state) => state.setLocale);
  const t = useCallback((key: UiKey) => ui[locale][key], [locale]);
  const view = useCallback((product: Product) => lotView(product, locale), [locale]);
  const c = pageCopy[locale];
  const category = useCallback((name: string) => catLabel[locale][name] ?? name, [locale]);
  return { locale, setLocale, t, view, c, category };
}
